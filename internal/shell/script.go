package shell

import (
	"fmt"
	"path/filepath"
	"strings"
)

// GenerationFile, in GitPersona's configuration folder next to binDir, holds
// a value GitPersona changes each time it saves a change. The prompt
// functions keep their last answer while the directory, the repository it is
// in and this value stay the same, so a prompt drawn again in the same place
// starts no process.
const GenerationFile = "generation"

// Script returns the integration script for a shell. It moves binDir (where
// GitPersona's gh and glab entries live) to the front of PATH, exactly once,
// even when something like macOS path_helper moved it back; and it defines
// gitpersona_prompt for prompts, plus prompt items for tide (fish) and
// Powerlevel10k (zsh). It is printed by `gitpersona init <shell>`.
//
// gitpersona_prompt runs `gitpersona prompt` only when its answer can have
// changed: another directory, a repository created or removed above it, or a
// change GitPersona saved (GenerationFile). Otherwise it repeats its last
// answer using shell builtins only. Called as $(gitpersona_prompt) it runs in
// a subshell and cannot keep the answer; the tide item and the Powerlevel10k
// segment call it directly.
func Script(k Kind, binDir string) string {
	dir := quote(binDir)
	gen := quote(filepath.Join(filepath.Dir(binDir), GenerationFile))
	switch k {
	case Fish:
		return fmt.Sprintf(`# GitPersona shell integration (generated by "gitpersona init fish").
if test -d %[1]s
    set -gx PATH %[1]s (string match -v -- %[1]s $PATH)
end

set -g __gitpersona_key ''
set -g __gitpersona_value ''
function gitpersona_prompt --description 'Account GitPersona applies here'
    set -l generation ''
    test -r %[2]s; and read generation < %[2]s
    set -l d $PWD
    set -l repo ''
    while test -n "$d"
        if test -e "$d/.git"; or begin; test -e "$d/HEAD"; and test -d "$d/objects"; and test -d "$d/refs"; end
            set repo $d
            break
        end
        set d (string replace -r '/[^/]*$' '' -- $d)
    end
    set -l key "$PWD|$repo|$generation|$argv"
    if test "$key" != "$__gitpersona_key"
        set -g __gitpersona_value (command gitpersona prompt $argv 2>/dev/null)
        set -g __gitpersona_key $key
    end
    test -n "$__gitpersona_value"; and printf '%%s\n' $__gitpersona_value
end

# tide: add "gitpersona" to tide_left_prompt_items or tide_right_prompt_items.
function _tide_item_gitpersona
    gitpersona_prompt >/dev/null
    test -n "$__gitpersona_value"; and _tide_print_item gitpersona "👤 $__gitpersona_value"
end
`, dir, gen)
	case Zsh:
		return fmt.Sprintf(`# GitPersona shell integration (generated by "gitpersona init zsh").
if [[ -d %[1]s ]]; then
  path=(%[1]s ${path:#%[1]s})
  export PATH
fi

__gitpersona_key=
__gitpersona_value=
gitpersona_prompt() {
  local generation= d=$PWD repo= key
  [[ -r %[2]s ]] && read -r generation < %[2]s
  while [[ -n $d ]]; do
    if [[ -e $d/.git ]] || [[ -e $d/HEAD && -d $d/objects && -d $d/refs ]]; then
      repo=$d
      break
    fi
    d=${d%%/*}
  done
  key="$PWD|$repo|$generation|$*"
  if [[ $key != "$__gitpersona_key" ]]; then
    __gitpersona_value=$(command gitpersona prompt "$@" 2>/dev/null)
    __gitpersona_key=$key
  fi
  [[ -n $__gitpersona_value ]] && printf '%%s\n' "$__gitpersona_value"
  return 0
}

# Powerlevel10k: add "gitpersona" to POWERLEVEL9K_LEFT_PROMPT_ELEMENTS or _RIGHT_.
prompt_gitpersona() {
  gitpersona_prompt >/dev/null
  [[ -n $__gitpersona_value ]] && p10k segment -t "👤 $__gitpersona_value"
}
`, dir, gen)
	default:
		return fmt.Sprintf(`# GitPersona shell integration (generated by "gitpersona init bash").
if [[ -d %[1]s ]]; then
  IFS=: read -r -a __gitpersona_parts <<< "$PATH"
  PATH=%[1]s
  for __gitpersona_part in "${__gitpersona_parts[@]}"; do
    [[ -z "$__gitpersona_part" || "$__gitpersona_part" == %[1]s ]] || PATH="$PATH:$__gitpersona_part"
  done
  export PATH
  unset __gitpersona_parts __gitpersona_part
fi

__gitpersona_key=
__gitpersona_value=
gitpersona_prompt() {
  local generation= d=$PWD repo= key
  [[ -r %[2]s ]] && read -r generation < %[2]s
  while [[ -n $d ]]; do
    if [[ -e $d/.git ]] || [[ -e $d/HEAD && -d $d/objects && -d $d/refs ]]; then
      repo=$d
      break
    fi
    d=${d%%/*}
  done
  key="$PWD|$repo|$generation|$*"
  if [[ $key != "$__gitpersona_key" ]]; then
    __gitpersona_value=$(command gitpersona prompt "$@" 2>/dev/null)
    __gitpersona_key=$key
  fi
  [[ -n $__gitpersona_value ]] && printf '%%s\n' "$__gitpersona_value"
  return 0
}
`, dir, gen)
	}
}

// quote quotes a path for fish, zsh and bash. All three accept single quotes,
// and an embedded single quote is written by closing, escaping and reopening.
func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
