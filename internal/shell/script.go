package shell

import (
	"fmt"
	"strings"
)

// Script returns the integration script for a shell. It moves binDir (where
// GitPersona's gh and glab entries live) to the front of PATH, exactly once,
// even when something like macOS path_helper moved it back; and it defines
// gitpersona_prompt for prompts, plus prompt items for tide (fish) and
// Powerlevel10k (zsh). It is printed by `gitpersona init <shell>`.
func Script(k Kind, binDir string) string {
	dir := quote(binDir)
	switch k {
	case Fish:
		return fmt.Sprintf(`# GitPersona shell integration (generated by "gitpersona init fish").
if test -d %[1]s
    set -gx PATH %[1]s (string match -v -- %[1]s $PATH)
end

function gitpersona_prompt --description 'Account GitPersona applies here'
    command gitpersona prompt $argv 2>/dev/null
end

# tide: add "gitpersona" to tide_left_prompt_items or tide_right_prompt_items.
function _tide_item_gitpersona
    set -l account (gitpersona_prompt)
    test -n "$account"; and _tide_print_item gitpersona "👤 $account"
end
`, dir)
	case Zsh:
		return fmt.Sprintf(`# GitPersona shell integration (generated by "gitpersona init zsh").
if [[ -d %[1]s ]]; then
  path=(%[1]s ${path:#%[1]s})
  export PATH
fi

gitpersona_prompt() {
  command gitpersona prompt "$@" 2>/dev/null
}

# Powerlevel10k: add "gitpersona" to POWERLEVEL9K_LEFT_PROMPT_ELEMENTS or _RIGHT_.
prompt_gitpersona() {
  local account
  account="$(gitpersona_prompt)"
  [[ -n "$account" ]] && p10k segment -t "👤 $account"
}
`, dir)
	default:
		return fmt.Sprintf(`# GitPersona shell integration (generated by "gitpersona init bash").
if [[ -d %[1]s ]]; then
  IFS=: read -r -a __gitpersona_parts <<< "$PATH"
  PATH=%[1]s
  for __gitpersona_part in "${__gitpersona_parts[@]}"; do
    [[ -z "$__gitpersona_part" || "$__gitpersona_part" == %[1]s ]] || PATH="$PATH:$__gitpersona_part"
  done
  export PATH
  unset __gitpersona_parts __gitpersona_part
fi

gitpersona_prompt() {
  command gitpersona prompt "$@" 2>/dev/null
}
`, dir)
	}
}

// quote quotes a path for fish, zsh and bash. All three accept single quotes,
// and an embedded single quote is written by closing, escaping and reopening.
func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
